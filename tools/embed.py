#!/usr/bin/env python3
"""Embed an HTML page into a C header: embed.py page.html out.h SYMBOL"""
import sys

src, dst = sys.argv[1], sys.argv[2]
name = sys.argv[3] if len(sys.argv) > 3 else "WEBUI_HTML"
data = open(src, "rb").read()

lines = []
for i in range(0, len(data), 20):
    chunk = data[i:i + 20]
    lines.append("  " + ",".join(str(b) for b in chunk) + ",")

with open(dst, "w") as f:
    f.write("/* Generated by tools/embed.py - do not edit. */\n")
    f.write("#pragma once\n#include <stddef.h>\n\n")
    f.write("static const char %s[] = {\n" % name)
    f.write("\n".join(lines))
    f.write("\n  0\n};\n")
    f.write("static const size_t %s_LEN = %d;\n" % (name, len(data)))
